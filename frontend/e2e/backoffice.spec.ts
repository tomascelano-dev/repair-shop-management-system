import { expect, test, type Page } from '@playwright/test'
import { createOrderViaUi, ensureCashOpen, login, moveOrderTo } from './helpers'

async function pickItem(page: Page, placeholder: string | RegExp, text: string) {
  const input = page.getByPlaceholder(placeholder)
  await input.fill(text)
  await page.getByRole('button', { name: new RegExp(text) }).first().click()
}

test('stock: create an item, adjust it, buy it from a supplier and send some to another branch', async ({ page }) => {
  test.setTimeout(120_000)
  const ts = Date.now()
  const sku = `E2E-${ts}`
  await login(page, 'admin')

  await page.goto('/inventory')
  await page.getByRole('button', { name: '+ Nuevo ítem' }).click()
  const form = page.getByRole('dialog')
  await form.getByLabel('SKU').fill(sku)
  await form.getByLabel('Nombre').fill(`Repuesto E2E ${ts}`)
  await form.getByLabel('Stock inicial').fill('2')
  await form.getByLabel('Stock mínimo').fill('5')
  await form.getByLabel('Costo unitario').fill('1000')
  await form.getByLabel('Se vende en mostrador').check()
  await form.getByLabel('Precio de venta').fill('2500')
  await form.getByRole('button', { name: 'Crear ítem' }).click()
  await expect(page.getByText('Ítem creado')).toBeVisible()

  await page.getByPlaceholder(/Buscar por nombre, SKU/).fill(sku)
  const row = page.getByRole('row', { name: new RegExp(sku) })
  await expect(row).toContainText('bajo')
  await row.click()
  await page.getByRole('button', { name: 'Ajustar stock' }).click()
  const adjust = page.getByRole('dialog', { name: 'Ajustar stock' })
  await adjust.getByLabel('Cantidad que ingresa').fill('3')
  await adjust.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByText('Stock actualizado')).toBeVisible()
  await page.keyboard.press('Escape')

  // Purchase order with a new supplier, ordered and received.
  await page.goto('/purchases')
  await page.getByRole('button', { name: '+ Nueva orden de compra' }).click()
  await page.getByRole('button', { name: 'Nuevo proveedor' }).click()
  const supplier = page.getByRole('dialog', { name: 'Nuevo proveedor' })
  await supplier.getByLabel('Nombre').fill(`Proveedor E2E ${ts}`)
  await supplier.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByText('Proveedor creado')).toBeVisible()
  await pickItem(page, 'Buscar repuesto para pedir…', sku)
  await page.getByRole('button', { name: 'Guardar borrador' }).click()
  await expect(page.getByText(/creada/)).toBeVisible()
  await page.getByRole('row', { name: new RegExp(`Proveedor E2E ${ts}`) }).click()
  await page.getByRole('button', { name: 'Marcar como pedida' }).click()
  await expect(page.getByText('Marcada como pedida')).toBeVisible()
  await page.getByRole('button', { name: 'Recibir mercadería' }).click()
  await page.getByRole('button', { name: 'Confirmar recepción' }).click()
  await expect(page.getByText('Mercadería recibida completa')).toBeVisible()
  await page.keyboard.press('Escape')

  // A second branch, then a stock transfer to it.
  await page.goto('/settings?tab=branches')
  await page.getByRole('button', { name: '+ Nueva sucursal' }).click()
  await page.getByRole('dialog').getByLabel('Nombre').fill(`Sucursal E2E ${ts}`)
  await page.getByRole('button', { name: 'Crear sucursal' }).click()
  await expect(page.getByText(`Sucursal Sucursal E2E ${ts} creada`)).toBeVisible()

  await page.goto('/transfers')
  await page.getByRole('button', { name: '+ Nueva transferencia' }).click()
  await page.getByLabel('Sucursal de destino').selectOption({ label: `Sucursal E2E ${ts}` })
  await pickItem(page, 'Agregar ítem a transferir…', sku)
  await page.getByRole('button', { name: 'Enviar', exact: true }).click()
  await expect(page.getByText(/Transferencia .* enviada/)).toBeVisible()
  await expect(page.getByRole('row', { name: new RegExp(`Sucursal E2E ${ts}`) }).first()).toContainText('En tránsito')
})

test('admin: settings, invitations, refunds and closing the register', async ({ page }) => {
  test.setTimeout(120_000)
  const ts = Date.now()
  await login(page, 'admin')

  await page.goto('/settings?tab=operation')
  await page.getByLabel('Garantía por defecto (días)').fill('120')
  await page.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(page.getByText('Configuración guardada')).toBeVisible()

  await page.goto('/settings?tab=users')
  await page.getByRole('button', { name: '+ Invitar usuario' }).click()
  await page.getByRole('dialog').getByLabel('Nombre').fill('Técnica E2E')
  await page.getByRole('dialog').getByLabel('Email').fill(`tecnica.${ts}@example.com`)
  await page.getByRole('button', { name: 'Crear invitación' }).click()
  await expect(page.getByLabel('Link')).toHaveValue(/\/invitacion\?token=/)
  await page.getByRole('button', { name: 'Listo' }).click()

  await page.goto('/settings?tab=templates')
  await page.getByRole('button', { name: /Listo para retirar/ }).first().click()
  const editor = page.getByRole('dialog')
  await editor.getByRole('button', { name: 'customer_first_name', exact: true }).click()
  await expect(editor.getByRole('textbox', { name: 'Texto' })).toHaveValue(/\{\{customer_first_name\}\}/)
  await editor.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByText('Plantilla guardada')).toBeVisible()

  // Sell, refund part of it and close the register.
  await ensureCashOpen(page)
  await page.goto('/pos')
  await page.getByRole('searchbox').fill('7798000000017')
  await page.getByRole('searchbox').press('Enter')
  await page.getByRole('searchbox').fill('7798000000017')
  await page.getByRole('searchbox').press('Enter')
  await page.getByRole('button', { name: 'Cobrar (F4)' }).click()
  await page.getByRole('button', { name: 'Confirmar cobro' }).click()
  await expect(page.getByText(/Venta V-\d+ registrada/)).toBeVisible()
  await page.getByRole('button', { name: 'Nueva venta' }).click()

  await page.goto('/sales')
  await page.locator('tbody tr').first().click()
  await page.getByRole('button', { name: 'Devolución' }).click()
  await page.getByLabel(/Cantidad a devolver/).fill('1')
  await page.getByRole('button', { name: /^Devolver \$/ }).click()
  await expect(page.getByText('Devolución registrada')).toBeVisible()
  await page.keyboard.press('Escape')

  await page.goto('/cash')
  await page.getByRole('button', { name: 'Cerrar caja' }).click()
  await page.getByRole('button', { name: 'Ingresar total' }).click()
  const expected = (await page.locator('p:has-text("Esperado") span.tabular-nums').first().textContent()) ?? '0'
  await page.getByLabel('Efectivo contado').fill(expected.replace(/[^\d,]/g, ''))
  await page.getByRole('dialog').getByRole('button', { name: 'Cerrar caja' }).click()
  const result = page.getByRole('dialog', { name: /Turno #\d+ cerrado/ })
  await expect(result).toBeVisible()
  await expect(result.getByText('Sin diferencia')).toBeVisible()
  await page.getByRole('button', { name: 'Listo' }).click()
  await expect(page.getByText('La caja está cerrada')).toBeVisible()
})

test('the customer approves the quote from the portal', async ({ page, browser }) => {
  test.setTimeout(120_000)
  await login(page, 'admin')
  await createOrderViaUi(page, 'La batería dura muy poco')
  await moveOrderTo(page, 'En diagnóstico')

  await page.getByRole('tab', { name: /^Presupuestos/ }).click()
  await page.getByRole('button', { name: '+ Armar presupuesto' }).click()
  await page.getByLabel('Precio unit.').first().fill('18000')
  await page.getByRole('button', { name: 'Guardar borrador' }).click()
  await page.getByRole('button', { name: 'Enviar al cliente' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Enviar', exact: true }).click()
  await page.getByRole('button', { name: 'Listo' }).click()
  const trackingUrl = await page.getByRole('link', { name: 'abrir' }).getAttribute('href')

  const anonymous = await browser.newContext()
  const portal = await anonymous.newPage()
  await portal.goto(new URL(trackingUrl!).pathname)
  await expect(portal.getByText('La batería dura muy poco')).toBeVisible()
  await portal.getByRole('button', { name: 'Aprobar' }).click()
  await portal.getByRole('button', { name: 'Sí, aprobar' }).click()
  await expect(portal.getByText('Aprobado', { exact: true })).toBeVisible()
  await anonymous.close()

  await page.reload()
  await page.getByRole('tab', { name: /^Presupuestos/ }).click()
  await expect(page.getByText('Aprobado', { exact: true }).first()).toBeVisible()
})
